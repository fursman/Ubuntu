-- Machine-local files, each generated by setup.sh:
--   env-local   NVIDIA env vars and DRM devices, derived from the hardware
--   polkit-local  the polkit agent this release actually ships
--
-- pcall, not require, on purpose. `source =` in hyprlang failed softly on a
-- missing file; a bare require() raises, and a raised error in a Lua config
-- registers NO binds at all and drops Hyprland into emergency mode with only
-- SUPER+Q. A machine missing one generated file should lose that file's
-- settings, not its keyboard.
local function optional(mod)
    local ok, err = pcall(require, mod)
    if not ok then
        -- print(), not hl.log(): there is no hl.log, and this is the error
        -- path -- a call that does not exist here would defeat the whole
        -- point. print is plain Lua and lands in the Hyprland log.
        print("hyprland.lua: optional module '" .. mod .. "' not loaded: " .. tostring(err))
    end
    return ok
end

